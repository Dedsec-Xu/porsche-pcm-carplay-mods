"""Derive the CarPlay control from this firmware's native AUX rotary popup.

This only generates source. It does not install anything on the head unit.
"""
from pathlib import Path
import re

root = Path(__file__).parent
original = (root.parent / 'hmi-java/de/audi/tghu/tone/hmi/pgen2high/ToneScreenBag1.java').read_text()
start = original.index('    public static Screen soundVolumeAux(')
end = original.index('    public static Screen soundVolumeBluetooth(', start)
method = original[start:end]
assert method.count('setID(1000114)') == 1
assert method.count('setTextIds(new int[]{1000724})') == 1
method = method.replace('soundVolumeAux(', 'create(')
method = method.replace('1000129', 'pcm.PromptRuntime.MODEL_ID')
method = method.replace('setID(1000114)', 'setID(POPUP_ID)')
method = method.replace('setTextIds(new int[]{1000724})', 'setText("CarPlay Music Level")')
method = method.replace('setTextIds(new int[]{1000909})', 'setText("5: No reduction")')
method = method.replace('setMiddleIsZero(true)', 'setMiddleIsZero(false)')
# RangeModel listeners perform the update; do not send the native tone event.
method = re.sub(r'^.*\.set(?:LongPressEvent|Event)\(1000094\);\n', '', method, flags=re.M)
method = method.replace('setModelIDs(new int[]{pcm.PromptRuntime.MODEL_ID})', 'setModelIDs(new int[0])')
method = method.replace('setEventIDs(new int[]{1000094})', 'setEventIDs(new int[0])')
imports = '\n'.join(line for line in original.splitlines() if line.startswith('import '))
output = ('package de.audi.tghu.tone.hmi.pgen2high;\n\n' + imports +
          '\n\n/** Native rotary popup; generated by build_native_popup.py. */\n' +
          'public final class PromptRotaryPopup {\n' +
          '    public static final int POPUP_ID = 1000140;\n' + method + '}\n')
(root / 'src/pcm/PromptRotaryPopup.java').write_text(output)
print('Generated native rotary popup, ID 1000140, model 1000162')
